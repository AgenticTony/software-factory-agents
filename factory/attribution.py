"""AI-attribution patterns — the ONE list L0 and publish share (F-42).

Five commits on this repo's ``main`` carry machine-written attribution
(#22, #58, #61, #82, #86) because the implementer's CLI appends
``Co-Authored-By: Claude <noreply@anthropic.com>`` trailers (and
``Generated with …`` PR footers) by default. On a client repo that is a
contract and trust problem, not a style one, so F-42 refuses the class at
both places it could leave the factory:

* :func:`factory.l0.run_l0` scans the commit messages between the
  merge-base and head and FAILs with an ``attribution_trailer`` finding
  (AC-1) — before anything is pushed.
* :func:`factory.publish.gh_pr_create` refuses a PR title or body
  carrying the same patterns (AC-2) — so a squash commit, whose message
  GitHub builds from the PR title and body, cannot inherit one either.

The list matches exactly the AI classes BUILD-ORDER F-42 AC-1 names: a
``Co-Authored-By`` trailer **naming an AI author** (an assistant name or
this factory's own seat identities — the machine co-authoring its work)
**or an AI vendor address**, and a ``Generated with`` footer. A human
``Co-Authored-By`` passes: a human crediting a human is what the trailer
exists for. Over-matching (a human genuinely named Claude) fails closed —
the branch FAILs and a human reads it; under-matching silently publishes
an attribution the contract forbids.
"""

from __future__ import annotations

import re

# (name, pattern) — the name rides into findings and refusals so the
# implementer and the owner see WHICH class fired, not just that one did.
# Trailer lines are matched where a squash-merged body can carry them:
# bare, quoted (GitHub's "> " merge attribution), or in a list.
ATTRIBUTION_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "co_author_ai_author",
        # An assistant or agent name in the credited author. The factory's
        # own seat identities (Software Factory, Factory Implementer …)
        # are the AI author here — the exact shape #58/#61 shipped.
        re.compile(
            r"^[ \t>[|*-]*co-authored-by:[^\n]*\b("
            r"claude|anthropic|copilot|cursor|codex|gemini|chatgpt|gpt-?\d"
            r"|openai|deepseek|glm|qwen|kimi|moonshot|mistral|llama"
            r"|software factory|factory implementer"
            r")\b",
            re.IGNORECASE | re.MULTILINE,
        ),
    ),
    (
        "co_author_ai_vendor_address",
        # The address is an AI vendor's even when the name isn't.
        # ``copilot@github.com`` is named exactly: GitHub's human noreply
        # addresses are ``<login>@users.noreply.github.com`` and must pass.
        re.compile(
            r"^[ \t>[|*-]*co-authored-by:[^\n]*<[^\n>]*@("
            r"anthropic\.com|openai\.com|cursor\.sh|character\.ai"
            r")>\s*$"
            r"|^[ \t>[|*-]*co-authored-by:[^\n]*<copilot@github\.com>\s*$",
            re.IGNORECASE | re.MULTILINE,
        ),
    ),
    (
        "generated_with_footer",
        # The CLI's own PR footer and its hand-typed imitations
        # ("🤖 Generated with [Claude Code](…)", "Generated with Claude
        # Code"). ``git format-patch`` says "Generated by", not "with",
        # so the phrase itself is distinctive.
        re.compile(r"generated with[^\n]{0,160}", re.IGNORECASE),
    ),
)


def attribution_match(*texts: str) -> tuple[str, str] | None:
    """The first AI-attribution hit across ``texts``.

    Args:
        *texts: The surfaces to scan — a commit message, a PR title, a PR
            body — each in full; the patterns are line-anchored where a
            trailer is.

    Returns:
        ``(pattern name, matched line stripped)`` for the first match, in
        :data:`ATTRIBUTION_PATTERNS` order, or ``None`` when every text is
        free of AI attribution.
    """
    for name, pattern in ATTRIBUTION_PATTERNS:
        for text in texts:
            match = pattern.search(text or "")
            if match:
                # The full source line, not just the matched span — a
                # finding that names the trailer names the whole line
                # (the address with the author, the footer with its link).
                end = text.find("\n", match.start())
                line = text[match.start():end if end != -1 else len(text)]
                return name, line.strip()
    return None
